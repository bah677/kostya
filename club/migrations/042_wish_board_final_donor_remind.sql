-- Второе напоминание дарителю — предупреждение перед возвратом просьбы.
--
-- Напоминание было одно, через 6 часов после отклика, и на этом всё. При
-- таймауте в неделю человек успевал про просьбу забыть: из 44 завершённых
-- откликов 26 кончились молчаливым таймаутом, а не отказом. Просьбы при этом
-- стояли замороженными 90% своей жизни (см. docs/wish_board_audit.md).
--
-- Теперь два касания: раннее «вот что дальше» и позднее «просьба уйдёт
-- через N часов» — чтобы человек либо успел, либо честно вернул её в ленту.
ALTER TABLE wish_requests
  ADD COLUMN IF NOT EXISTS donor_final_reminded_at TIMESTAMPTZ NULL;
