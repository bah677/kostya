_NAME_BAD_RE = re.compile(r"^[\d\W_]+$", re.UNICODE)


def safe_first_name(raw: str | None) -> str | None:
    name = (raw or "").strip()
    if not name or len(name) > 30:
        return None
    if _NAME_BAD_RE.match(name):
        return None
    return name


def name_suffix_hello(raw: str | None) -> str:
    n = safe_first_name(raw)
    return f", {n}" if n else ""


def t16_name_line(raw: str | None) -> str:
    n = safe_first_name(raw)
    if n:
        return T16_NAME_LINE.format(name=n)
    return T16_NAME_LINE_FALLBACK


def clip_about(text: str | None, *, limit: int = 300) -> str:
    t = re.sub(r"\s+", " ", (text or "").strip())
    if len(t) <= limit:
        return t
    cut = t[: limit - 1].rsplit(" ", 1)[0].rstrip()
    if len(cut) < 40:
        cut = t[: limit - 1].rstrip()
    return cut + "…"


def normalize_answer_text(text: str | None) -> str:
    t = (text or "").strip()
    m = re.match(r"^\[голосовое:\s*(.*)\]\s*$", t, re.DOTALL | re.IGNORECASE)
    if m:
        t = (m.group(1) or "").strip()
    t = re.sub(r"\s+", " ", t).strip()
    return t
