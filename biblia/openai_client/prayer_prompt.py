# Обратная совместимость импортов.
PRAYER_COMPOSE_SYSTEM_PROMPT = PRAYER_COMPOSE_SYSTEM_PROMPT_A


def pick_prayer_compose_variant(
    user_id: int,
    *,
    mode: Optional[str] = None,
    b_percent: int = 50,
) -> PrayerComposeVariant:
    """
    mode:
      A  — всегда A
      B  — всегда B
      AB — sticky A/B по user_id (доля B = b_percent)
    """
    from config import config

    raw = (mode if mode is not None else getattr(config, "PRAYER_COMPOSE_PROMPT_VARIANT", "A"))
    mode_norm = str(raw or "A").strip().upper()
    if mode_norm in {"A", "B"}:
        return mode_norm  # type: ignore[return-value]
    # AB / RANDOM / TEST
    pct = int(b_percent if b_percent is not None else getattr(config, "PRAYER_COMPOSE_AB_B_PERCENT", 50) or 50)
    pct = max(0, min(100, pct))
    digest = hashlib.md5(f"prayer_compose_ab:{int(user_id)}".encode("utf-8")).hexdigest()
    bucket = int(digest[:8], 16) % 100
    return "B" if bucket < pct else "A"


def resolve_prayer_compose_system_prompt(variant: PrayerComposeVariant) -> str:
    if variant == "B":
        return PRAYER_COMPOSE_SYSTEM_PROMPT_B
    return PRAYER_COMPOSE_SYSTEM_PROMPT_A


def prayer_compose_request_kind(variant: PrayerComposeVariant) -> str:
    return f"personal_prayer_compose_{variant.lower()}"


def prayer_compose_max_tokens(variant: PrayerComposeVariant) -> int:
    from config import config

    if variant == "B":
        return max(800, int(getattr(config, "PRAYER_COMPOSE_MAX_TOKENS_B", 8192) or 8192))
    return max(400, int(getattr(config, "PRAYER_COMPOSE_MAX_TOKENS_A", 4096) or 4096))


