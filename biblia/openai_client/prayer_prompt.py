def prayer_text_looks_complete(text: str) -> bool:
    """Эвристика: молитва доведена до финала (амИнь в хвосте)."""
    t = (text or "").strip()
    if len(t) < 120:
        return False
    # амИнь / аминь / Аминь; нормализуем і/i → и
    tail = t[-200:].casefold().replace("і", "и").replace("i", "и")
    return "аминь" in tail
